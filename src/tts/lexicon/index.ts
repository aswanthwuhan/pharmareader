/**
 * Text normalisation for TTS: turn pharmacology notation into words the speech
 * engines get right ("t½" → "half-life", "CYP3A4" → "C Y P three eigh four").
 *
 * Built-in entries live in `pharma-lexicon.json` and are seeded into
 * `db.lexicon` on first use. Every row carries a stable id: `b-<n>` for the core
 * rules, `rx-<n>` for the drug-name respellings, `med-<n>` for the medical
 * morphology rules and `term-<n>` for the screened medical-term respellings, so
 * a re-seed can update the rows in place while keeping the user's on/off
 * choices. Rules are applied in *file* order (not id order) — the JSON is
 * ordered from the most specific pattern to the generic glyph rules at the end.
 * User entries always run first, in creation order, then the built-ins.
 *
 * The `term-` rows are a word list, not a handful of patterns, so they are
 * compiled into one `Map` keyed by the lower-cased word and applied in a single
 * pass over the chapter's word tokens (`compiledRules`); every other row runs
 * as a regex. Both paths keep `expand()` idempotent.
 *
 * On Android the words are spoken by sherpa-onnx, which looks a word up in the
 * model's own lexicon (`lexicon-us-en.txt`) *first* and only falls back to
 * eSpeak for unknown words. A respelling there can turn a word the model
 * already says correctly into an unknown token, so `expand(text, 'kokoro')` on
 * a native build skips the rows listed in `kokoro-native-known.json`. The web
 * build (kokoro-js) has no such lexicon and keeps every row.
 *
 * Convention for letter names: espeak-ng reads a bare capital "A" as the
 * article ("uh"), so letter sequences are written with dots between the
 * capitals ("A.C.E", "A.N.S", "A.T.P-ace") and a lone A as "eigh", which is the
 * only spelling espeak turns into /eɪ/. See `drug-respellings.md`,
 * `medical-respellings.md` and `term-respellings.md`.
 */
import { Capacitor } from '@capacitor/core';
import rawNativeKnown from './kokoro-native-known.json?raw';
import rawLexicon from './pharma-lexicon.json?raw';
import { db } from '../../core/db';
import type { LexiconEntry } from '../../core/types';
import { sha256Hex } from '../cache';

interface RawEntry {
  id: string;
  pattern: string;
  replacement: string;
  isRegex: boolean;
}

export const BUILTIN_LEXICON: readonly RawEntry[] = JSON.parse(rawLexicon) as RawEntry[];

/**
 * Rows whose word the Android Kokoro model lexicon already pronounces correctly
 * (for the `-ine` rows: with the final /iːn/, not /aɪn/). Generated by
 * `.tmp/lexicon-worker/check-native-known.mjs`; see `term-respellings.md`
 * § *Per-engine: native Kokoro*. Do not hand-edit.
 */
const NATIVE_KOKORO_KNOWN: ReadonlySet<string> = new Set(JSON.parse(rawNativeKnown) as string[]);

/** Which rules a build may apply: the model lexicon changes what a respelling does. */
type LexiconVariant = 'default' | 'native';

/** Suffixes the plural/possessive rule tries, the possessive before the bare plural. */
const SUFFIXES = ['\u2019s', "'s", 's'] as const;

/** Shortest word the suffix rule may strip: `gas`, `news` and the like stay put. */
const MIN_SUFFIXED_WORD = 5;

/** Where each built-in applies in the pipeline: the order it has in the file. */
const BUILTIN_ORDER: ReadonlyMap<string, number> = new Map(BUILTIN_LEXICON.map((e, i) => [e.id, i]));

/** The seeded rows, in file order, before any user toggle is applied. */
function builtinRecords(): LexiconEntry[] {
  return BUILTIN_LEXICON.map((e) => ({
    id: e.id,
    pattern: e.pattern,
    replacement: e.replacement,
    isRegex: e.isRegex,
    source: 'builtin',
    enabled: true,
  }));
}

/** Position in the pipeline; unknown ids sort last so a stale row cannot jump ahead. */
function builtinOrder(id: string): number {
  return BUILTIN_ORDER.get(id) ?? Number.MAX_SAFE_INTEGER;
}

/**
 * Which toggleable group an entry belongs to. Drug respellings and medical
 * respellings can each be switched off as a group without touching the
 * notation rules.
 */
export function entryGroup(id: string): 'core' | 'drug' | 'medical' | 'term' {
  if (id.startsWith('rx-')) return 'drug';
  if (id.startsWith('med-')) return 'medical';
  if (id.startsWith('term-')) return 'term';
  return 'core';
}

/**
 * `\b[Oo]meprazole\b` → `omeprazole`; null for anything that is not a plain
 * whole-word rule. The `term-` rows are all of that shape, which lets them run
 * as one hash lookup per word instead of one regex pass per row.
 */
const WORD_ENTRY = /^\\b\[([A-Za-z])([A-Za-z])\]([A-Za-z]*)\\b$/;

function wordEntryKey(entry: LexiconEntry): string | null {
  if (!entry.isRegex) return null;
  const m = WORD_ENTRY.exec(entry.pattern);
  if (!m || m[1].toLowerCase() !== m[2].toLowerCase()) return null;
  return (m[1] + m[3]).toLowerCase();
}

// ---------------------------------------------------------------------------
// Seeding
// ---------------------------------------------------------------------------

let seeding: Promise<void> | null = null;

/** Create/refresh the built-in rows. Safe to call on every app start. */
export async function seedLexicon(): Promise<void> {
  if (!seeding) {
    seeding = seed().finally(() => {
      seeding = null;
    });
  }
  await seeding;
}

async function seed(): Promise<void> {
  const existing = await db.lexicon.where('source').equals('builtin').toArray();
  const byId = new Map(existing.map((e) => [e.id, e]));
  const wanted = builtinRecords();
  const wantedIds = new Set(wanted.map((e) => e.id));

  const changed: LexiconEntry[] = [];
  for (const next of wanted) {
    const prev = byId.get(next.id);
    const same =
      prev !== undefined &&
      prev.pattern === next.pattern &&
      prev.replacement === next.replacement &&
      prev.isRegex === next.isRegex;
    // Keep a toggle the user already made on this row.
    if (!same) changed.push({ ...next, enabled: prev ? prev.enabled : true });
  }
  const stale = existing.filter((e) => !wantedIds.has(e.id)).map((e) => e.id);

  if (changed.length > 0 || stale.length > 0) {
    await db.transaction('rw', db.lexicon, async () => {
      if (changed.length > 0) await db.lexicon.bulkPut(changed);
      if (stale.length > 0) await db.lexicon.bulkDelete(stale);
    });
    invalidate();
  }
}

// ---------------------------------------------------------------------------
// Expansion
// ---------------------------------------------------------------------------

export function invalidate(): void {
  enabledCache = null;
  versionCache = null;
  compiledCache = { default: null, native: null };
}

let enabledCache: LexiconEntry[] | null = null;
let versionCache: string | null = null;
let compiledCache: Record<LexiconVariant, CompiledRules | null> = { default: null, native: null };

interface CompiledRules {
  /** Whole-word respellings, keyed by lowercase word (the `term-` group). */
  wordMap: ReadonlyMap<string, string>;
  /**
   * The same rows unfiltered, for the plural/possessive rule only. The model
   * lexicon is keyed by the exact token, so `tetracyclines` is a word it does
   * not know even though it knows `tetracycline`; the stem's respelling is
   * still what the phone needs there.
   */
  stemMap: ReadonlyMap<string, string>;
  /** Everything else, still applied as an ordered list of regex/substring rules. */
  others: readonly LexiconEntry[];
}

const WORD = /[A-Za-z][A-Za-z'\u2019]*/g;

function compiledRules(entries: readonly LexiconEntry[], variant: LexiconVariant): CompiledRules {
  const cached = compiledCache[variant];
  if (cached) return cached;
  const skipKnown = variant === 'native';
  const wordMap = new Map<string, string>();
  const stemMap = new Map<string, string>();
  const others: LexiconEntry[] = [];
  for (const entry of entries) {
    const key = entry.id.startsWith('term-') ? wordEntryKey(entry) : null;
    if (key === null) {
      if (!(skipKnown && NATIVE_KOKORO_KNOWN.has(entry.id))) others.push(entry);
      continue;
    }
    stemMap.set(key, entry.replacement);
    if (!(skipKnown && NATIVE_KOKORO_KNOWN.has(entry.id))) wordMap.set(key, entry.replacement);
  }
  const compiled = { wordMap, stemMap, others };
  compiledCache[variant] = compiled;
  return compiled;
}

// A half-typed regex in the editor must never break playback.
const regexCache = new Map<string, RegExp | null>();

function regexFor(pattern: string): RegExp | null {
  let re = regexCache.get(pattern);
  if (re === undefined) {
    try {
      re = new RegExp(pattern, 'g');
    } catch {
      re = null;
    }
    regexCache.set(pattern, re);
  }
  return re;
}

/** Apply one entry to `text`. Exposed for the lexicon editor's preview column. */
export function applyEntry(text: string, entry: LexiconEntry): string {
  if (!entry.pattern) return text;
  if (!entry.isRegex) {
    // Plain substring; split/join so "$&" in a replacement stays literal.
    return text.split(entry.pattern).join(entry.replacement);
  }
  const re = regexFor(entry.pattern);
  return re ? text.replace(re, entry.replacement) : text;
}

async function enabledEntries(): Promise<LexiconEntry[]> {
  if (enabledCache) return enabledCache;
  await seedLexicon();
  const all = await db.lexicon.toArray();
  const user = all
    .filter((e) => e.source === 'user' && e.enabled)
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const builtin = all
    .filter((e) => e.source === 'builtin' && e.enabled)
    .sort((a, b) => builtinOrder(a.id) - builtinOrder(b.id));
  enabledCache = [...user, ...builtin];
  return enabledCache;
}

/**
 * One whole word: the exact entry if there is one, else — for a plural or a
 * possessive — the stem's respelling plus the suffix it was wearing.
 */
function respellToken(
  token: string,
  wordMap: ReadonlyMap<string, string>,
  stemMap: ReadonlyMap<string, string>,
): string | undefined {
  const lower = token.toLowerCase();
  const exact = wordMap.get(lower);
  if (exact !== undefined) return exact;
  if (lower.length < MIN_SUFFIXED_WORD) return undefined;
  for (const suffix of SUFFIXES) {
    if (!lower.endsWith(suffix)) continue;
    const stem = stemMap.get(lower.slice(0, -suffix.length));
    if (stem !== undefined) return stem + suffix;
  }
  return undefined;
}

/**
 * Rewrite `text` into something a speech engine pronounces correctly. Pass the
 * engine id (`'kokoro'`) to let a native build keep the words its model lexicon
 * already says correctly; without it every row applies, as on the web.
 */
export async function expand(text: string, engineId?: string): Promise<string> {
  const variant: LexiconVariant =
    engineId === 'kokoro' && Capacitor.isNativePlatform() ? 'native' : 'default';
  const { wordMap, stemMap, others } = compiledRules(await enabledEntries(), variant);
  let out = text;
  for (const entry of others) out = applyEntry(out, entry);
  // The `term-` respellings are whole-word substitutions; one tokenised pass
  // keeps a long term list from costing one regex pass per word.
  if (stemMap.size > 0) out = out.replace(WORD, (w) => respellToken(w, wordMap, stemMap) ?? w);
  // Symbol rules emit padded words ("↑" → " increases "); tidy the gaps they leave.
  return out
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\s+([,.;:!?])/g, '$1')
    .trim();
}

/** Short hash of the enabled rules, for tests and diagnostics. */
export async function lexiconVersion(): Promise<string> {
  if (versionCache) return versionCache;
  const sig = (await enabledEntries()).map((e) => `${e.pattern}\u0001${e.replacement}`).join('\u0002');
  versionCache = (await sha256Hex(sig)).slice(0, 12);
  return versionCache;
}

// ---------------------------------------------------------------------------
// Editor helpers (used by TtsSettings; keep writes here so the cache stays warm)
// ---------------------------------------------------------------------------

export function newUserEntryId(): string {
  // Timestamp-first ids keep user entries in creation order.
  return `u-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 7)}`;
}

/** All entries in expansion order: user rules first, then the built-ins. */
export async function listLexiconEntries(): Promise<LexiconEntry[]> {
  await seedLexicon();
  const all = await db.lexicon.toArray();
  return [
    ...all.filter((e) => e.source === 'user').sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)),
    ...all.filter((e) => e.source === 'builtin').sort((a, b) => builtinOrder(a.id) - builtinOrder(b.id)),
  ];
}

export async function saveUserEntry(entry: {
  id?: string;
  pattern: string;
  replacement: string;
  isRegex: boolean;
}): Promise<LexiconEntry> {
  const rec: LexiconEntry = {
    id: entry.id ?? newUserEntryId(),
    pattern: entry.pattern,
    replacement: entry.replacement,
    isRegex: entry.isRegex,
    source: 'user',
    enabled: true,
  };
  const prev = entry.id ? await db.lexicon.get(entry.id) : undefined;
  if (prev) rec.enabled = prev.enabled;
  await db.lexicon.put(rec);
  invalidate();
  return rec;
}

export async function deleteUserEntry(id: string): Promise<void> {
  await db.lexicon.delete(id);
  invalidate();
}

export async function setEntryEnabled(id: string, enabled: boolean): Promise<void> {
  await db.lexicon.update(id, { enabled });
  invalidate();
}
